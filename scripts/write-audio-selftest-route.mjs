import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

if (process.env.EXPO_PUBLIC_AUDIO_SELFTEST !== "1") {
  throw new Error("Refusing to generate the audio self-test route without EXPO_PUBLIC_AUDIO_SELFTEST=1");
}

if (process.env.GITHUB_ACTIONS !== "true") {
  throw new Error("Refusing to rewrite Expo Router entry files outside GitHub Actions");
}

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const layoutPath = join(repoRoot, "src", "app", "_layout.tsx");

mkdirSync(dirname(layoutPath), { recursive: true });
writeFileSync(
  layoutPath,
  `// Generated by scripts/write-audio-selftest-route.mjs for CI only.\nexport { default } from "../devtools/AudioSelfTestScreen";\n`,
  "utf8",
);

console.log(`Wrote ${layoutPath}`);
