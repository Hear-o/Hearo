import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

if (process.env.EXPO_PUBLIC_AUDIO_SELFTEST !== "1") {
  throw new Error("Refusing to generate the audio self-test route without EXPO_PUBLIC_AUDIO_SELFTEST=1");
}

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const routePath = join(repoRoot, "src", "app", "audio-selftest.tsx");

mkdirSync(dirname(routePath), { recursive: true });
writeFileSync(
  routePath,
  `// Generated by scripts/write-audio-selftest-route.mjs for CI only.\nexport { default } from "../devtools/AudioSelfTestScreen";\n`,
  "utf8",
);

console.log(`Wrote ${routePath}`);
